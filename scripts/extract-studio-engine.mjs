// Copies Concept Studio's document engine, unchanged, out of the reference file into
// src/lib/studio/engine.generated.js. Run: node scripts/extract-studio-engine.mjs
//
// Why: Phase 1 must produce the same letters and proposals as Studio (EL v3.31). Taking the
// engine code word for word, instead of rewriting it, makes parity hold by construction.
// The parity test (tests/studio-parity.test.mjs) then checks the output against the original.
//
// What is taken: the named entry points below and every top-level function or constant they
// use, in their original order. Anything that touches the browser page, Notion or the embedded
// images is left out and must be supplied by the app (listed in the generated file's header).
import { readFileSync, writeFileSync } from "node:fs";
import * as acorn from "acorn";
import * as walk from "acorn-walk";

const SRC = "reference/studio/studio-el-v3.31-redacted.html";
const OUT = "src/lib/studio/engine.generated.js";

// Entry points the app calls.
const ROOTS = [
  "EL_VERSION", "EL_VERSION_DATE", "TYPES", "BASIS", "FEE_PRESETS", "PAY_LABEL",
  "checks", "build", "pdfDoc", "fileName", "deriveType", "svcList", "payInfo", "firstInvoice", "feeVal", "feeText", "money", "fmtD",
  "t1Checks", "buildT1", "t1Names", "t1FileName", "T1_REL", "CRA_OPT", "CRA_GROUP",
  "pChecks", "pBuild", "pPdf", "pTotals", "pValidUntil", "pNewOption", "PSVC", "PKIND", "POPTS",
  "t1cCalc", "t1cSummary", "T1C_ITEMS", "T1C_TRIAGE", "T1C_OUT", "T1C",
  "TEMPLATES",
  // Screen logic that is pure and reused as is: fee lines follow the ticked services.
  "syncFees", "FEE_SVC", "SVC_UI", "IDS", "feeRow", "lastYE", "todayISO",
  // T1 standalone master wording (Studio shows it instead of issuing a letter) and previews.
  "t1TdHtml", "t1TdText", "t1Html", "pHtml", "pPack", "pbServices", "pbNum", "pbAnnual", "unesc", "esc",
];
// Top-level variables the screens read and change (Studio keeps them as page globals).
const MUTABLE = ["FEES", "T1C", "POPTS", "pRec"];
// Supplied by the app at run time (page, data or images), never copied.
const INJECTED = new Set(["$", "DB", "mcp", "LH", "SIG", "ILLUS", "document", "window", "localStorage", "pdfMake", "PDFLib"]);

const html = readFileSync(SRC, "utf8");
const m = html.match(/<script>\n([\s\S]*?)<\/script>\s*<\/body>/);
if (!m) throw new Error("Studio script block not found");
const code = m[1];
const ast = acorn.parse(code, { ecmaVersion: 2022, sourceType: "script" });

// Map each top-level name to its statement.
const decls = new Map();
for (const node of ast.body) {
  if (node.type === "FunctionDeclaration") decls.set(node.id.name, node);
  else if (node.type === "VariableDeclaration") for (const d of node.declarations) if (d.id.type === "Identifier") decls.set(d.id.name, node);
}

const take = new Set();
const injectedUsed = new Set();
const unknown = new Set();
const queue = [...ROOTS, ...MUTABLE];
while (queue.length) {
  const name = queue.shift();
  if (take.has(name)) continue;
  const node = decls.get(name);
  if (!node) { unknown.add(name); continue; }
  take.add(name);
  walk.full(node, (n) => {
    if (n.type !== "Identifier") return;
    if (INJECTED.has(n.name)) { injectedUsed.add(n.name); return; }
    if (decls.has(n.name) && !take.has(n.name)) queue.push(n.name);
  });
}

// Emit whole statements in original order (a statement may declare several names).
const stmts = [...new Set([...take].map((n) => decls.get(n)))].sort((a, b) => a.start - b.start);
const names = [...take].sort();
const header = `// GENERATED by scripts/extract-studio-engine.mjs from ${SRC}. Do not edit by hand.
// Concept Studio document engine, EL v3.31, copied word for word.
// Supplied by the app at run time: ${[...injectedUsed].sort().join(", ") || "nothing"}.
/* eslint-disable */
`;
const body = stmts.map((s) => code.slice(s.start, s.end)).join("\n");
const factory = `${header}
// Builds an isolated engine. "env" supplies what Studio read from the page:
//   DB (price floors and catalogue rows), $ (form fields, only where unavoidable), SIGNER and
//   SIGNER_TITLE overrides (owner settings), LH/SIG/ILLUS (image data URLs).
export function createStudioEngine(env = {}) {
  var DB = env.DB || { floors: [], cat: [] }, $ = env.$ || function () { return null; };
  var LH = env.LH || "", SIG = env.SIG || "", ILLUS = env.ILLUS || "";
${body.split("\n").map((l) => "  " + l).join("\n")}
  if (env.SIGNER) SIGNER = env.SIGNER;
  if (env.SIGNER_TITLE) SIGNER_TITLE = env.SIGNER_TITLE;
  // get/set for the page-level variables Studio's functions read and reassign.
  function __get(name) { switch (name) { ${MUTABLE.map((n) => `case "${n}": return ${n};`).join(" ")} } }
  function __set(name, v) { switch (name) { ${MUTABLE.map((n) => `case "${n}": ${n} = v; return;`).join(" ")} } }
  return { ${names.join(", ")}, __get, __set };
}
`;
writeFileSync(OUT, factory);
console.log(`Wrote ${OUT}: ${take.size} names, ${stmts.length} statements.`);
if (unknown.size) console.log("Not found (check ROOTS):", [...unknown].join(", "));
console.log("Uses from the app:", [...injectedUsed].join(", ") || "none");
