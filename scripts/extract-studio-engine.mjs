// Copies Concept Studio's document engine, unchanged, out of the reference file into
// src/lib/studio/engine.generated.js. Run: node scripts/extract-studio-engine.mjs
//
// Why: Phase 1 must produce the same letters and proposals as Studio (EL v3.31). Taking the
// engine code word for word, instead of rewriting it, makes parity hold by construction.
// The parity test (tests/studio-parity.test.mjs) then checks the output against the original.
//
// What is taken: the named entry points below and every top-level function or constant they
// use, in their original order. Anything that touches the browser page, Notion or the embedded
// images is left out and must be supplied by the app (listed in the generated file's header).
import { readFileSync, writeFileSync } from "node:fs";
import * as acorn from "acorn";
import * as walk from "acorn-walk";
import { wordifyStatement, WORD_FUNCTIONS, WORD_CONSTANTS, RUNTIME } from "./wordify.mjs";

const SRC = "reference/studio/studio-el-v3.31-redacted.html";
const OUT = "src/lib/studio/engine.generated.js";
const WORDING_OUT = "src/lib/studio/wording.generated.json";

// Entry points the app calls.
const ROOTS = [
  "EL_VERSION", "EL_VERSION_DATE", "TYPES", "BASIS", "FEE_PRESETS", "PAY_LABEL",
  "checks", "build", "pdfDoc", "fileName", "deriveType", "svcList", "payInfo", "firstInvoice", "feeVal", "feeText", "money", "fmtD",
  "t1Checks", "buildT1", "t1Names", "t1FileName", "T1_REL", "CRA_OPT", "CRA_GROUP",
  "pChecks", "pBuild", "pPdf", "pTotals", "pValidUntil", "pNewOption", "PSVC", "PKIND", "POPTS",
  "t1cCalc", "t1cSummary", "T1C_ITEMS", "T1C_TRIAGE", "T1C_OUT", "T1C",
  "TEMPLATES",
  // Screen logic that is pure and reused as is: fee lines follow the ticked services.
  "syncFees", "FEE_SVC", "SVC_UI", "IDS", "feeRow", "lastYE", "todayISO",
  // T1 standalone master wording (Studio shows it instead of issuing a letter) and previews.
  "t1TdHtml", "t1TdText", "t1Html", "pHtml", "render", "pkgOptions", "parseD", "PAY_NOTION", "TYPE_NOTION", "TYPES", "SIGNER", "SIGNER_TITLE", "FIRM", "pPack", "pbServices", "pbNum", "pbAnnual", "unesc", "esc",
];
// Top-level variables the screens read and change (Studio keeps them as page globals).
const MUTABLE = ["FEES", "T1C", "POPTS", "pRec"];
// Supplied by the app at run time (page, data or images), never copied.
const INJECTED = new Set(["$", "DB", "mcp", "LH", "SIG", "ILLUS", "document", "window", "localStorage", "pdfMake", "PDFLib"]);

const html = readFileSync(SRC, "utf8");
const m = html.match(/<script>\n([\s\S]*?)<\/script>\s*<\/body>/);
if (!m) throw new Error("Studio script block not found");
const code = m[1];
const ast = acorn.parse(code, { ecmaVersion: 2022, sourceType: "script" });

// Map each top-level name to its statement.
const decls = new Map();
for (const node of ast.body) {
  if (node.type === "FunctionDeclaration") decls.set(node.id.name, node);
  else if (node.type === "VariableDeclaration") for (const d of node.declarations) if (d.id.type === "Identifier") decls.set(d.id.name, node);
}

const take = new Set();
const injectedUsed = new Set();
const unknown = new Set();
const queue = [...ROOTS, ...MUTABLE];
while (queue.length) {
  const name = queue.shift();
  if (take.has(name)) continue;
  const node = decls.get(name);
  if (!node) { unknown.add(name); continue; }
  take.add(name);
  walk.full(node, (n) => {
    if (n.type !== "Identifier") return;
    if (INJECTED.has(n.name)) { injectedUsed.add(n.name); return; }
    if (decls.has(n.name) && !take.has(n.name)) queue.push(n.name);
  });
}

// Emit whole statements in original order (a statement may declare several names).
const stmts = [...new Set([...take].map((n) => decls.get(n)))].sort((a, b) => a.start - b.start);
const names = [...take].sort();
const header = `// GENERATED by scripts/extract-studio-engine.mjs from ${SRC}. Do not edit by hand.
// Concept Studio document engine, EL v3.31, copied word for word.
// Supplied by the app at run time: ${[...injectedUsed].sort().join(", ") || "nothing"}.
/* eslint-disable */
`;
// Wording pieces become editable (see scripts/wordify.mjs); everything else is copied as is.
const pieces = new Map();
const body = stmts.map((st) => {
  const name = st.type === "FunctionDeclaration" ? st.id.name : st.declarations?.[0]?.id?.name;
  if (!(WORD_FUNCTIONS.has(name) || WORD_CONSTANTS.has(name))) return code.slice(st.start, st.end);
  const r = wordifyStatement(code, st, name);
  for (const p of r.pieces) {
    const cur = pieces.get(p.key);
    if (cur) { if (!cur.fns.includes(p.fn)) cur.fns.push(p.fn); }
    else pieces.set(p.key, { key: p.key, text: p.text, fns: [p.fn], fills: p.fills });
  }
  return r.source;
}).join("\n");
const factory = `${header}
// Builds an isolated engine. "env" supplies what Studio read from the page:
//   DB (price floors and catalogue rows), $ (form fields, only where unavoidable), SIGNER and
//   SIGNER_TITLE overrides (owner settings), LH/SIG/ILLUS (image data URLs).
export function createStudioEngine(env = {}) {
  var DB = env.DB || { floors: [], cat: [] }, $ = env.$ || function () { return null; };
  var LH = env.LH || "", SIG = env.SIG || "", ILLUS = env.ILLUS || "";
${RUNTIME}
${body.split("\n").map((l) => "  " + l).join("\n")}
  if (env.SIGNER) SIGNER = env.SIGNER;
  if (env.SIGNER_TITLE) SIGNER_TITLE = env.SIGNER_TITLE;
  // The approved wording version in use (e.g. "EL v3.32"); the original is EL v3.31.
  if (env.EL_VERSION) EL_VERSION = env.EL_VERSION;
  if (env.EL_VERSION_DATE) EL_VERSION_DATE = env.EL_VERSION_DATE;
  // get/set for the page-level variables Studio's functions read and reassign.
  function __get(name) { switch (name) { ${MUTABLE.map((n) => `case "${n}": return ${n};`).join(" ")} } }
  function __set(name, v) { switch (name) { ${MUTABLE.map((n) => `case "${n}": ${n} = v; return;`).join(" ")} } }
  return { ${names.join(", ")}, __get, __set };
}
`;
// One change to Studio's code (Hashim, Nov 11, 2026): a proposal "Next steps" line whose wording is
// set to blank in Templates is left out, so a step can be removed without leaving an empty number.
// With the original wording no line is blank, so the output is unchanged.
const OL = 'B.push({k:"ol",items:[';
const at = factory.indexOf(OL);
if (at < 0 || factory.indexOf(OL, at + 1) >= 0) throw new Error("Expected exactly one proposal Next steps list.");
const end = factory.indexOf("]});", at);
let patched = factory.slice(0, end) + "].filter(function(t){return __plain(t).trim()!==\"\";})});" + factory.slice(end + 4);
// Second change (front office batch, section 5, item 4): in Quotes, each option box lists its fee
// lines, so software is never folded into the monthly fee. Only when the app asks for it (P_LINES);
// without it the output is Studio's.
const POPTS = 'B.push({k:"popts",single:s.single,';
if (patched.split(POPTS).length !== 2) throw new Error("Expected exactly one proposal options block.");
// Third change, with P_LINES only: a fee line with no amount reads "Amount needed" in the preview,
// not "Included" (a blank amount already stops the proposal from being sent).
const LINE = 'return [l.svc,v.k==="num"?';
if (patched.split(LINE).length !== 2) throw new Error("Expected exactly one option fee line.");
// Fourth change, app screens only (P_NEED): a letter fee with no amount reads "Amount needed" in the
// preview, not a blank cell. The letter's checks already stop a Final with a blank amount.
const FEETEXT = 'function feeText(v){ var f=feeVal(v);';
if (patched.split(FEETEXT).length !== 2) throw new Error("Expected exactly one feeText.");
// Fifth change, with P_LINES only (Hashim, Nov 12, 2026): clients never see an annual total. The
// option boxes drop the "Annual value" row (screen and PDF), and the price floor (on the fee only)
// leaves software out. Staff screens still show the annual figure for the floor check.
const ANN_HTML = '+"<tr>"+"<td>"+"<b>"+__WH("w408a27b5e4", "Annual value", [])+"</b>"+"</td>"+"<td style=\\"text-align:right\\">"+"<b>"+(esc(o.annual))+"</b>"+"</td>"+"</tr>"';
const ANN_PDF = '.concat([[{text:__W("w408a27b5e4", "Annual value", []),bold:true},{text:o.annual,bold:true,alignment:"right"}]])';
const FLOOR = 's.opts.forEach(function(o){ var t=pTotals(o), nm=o.name||"An option";';
for (const x of [ANN_HTML, ANN_PDF, FLOOR]) if (patched.split(x).length !== 2) throw new Error("Expected exactly one: " + x.slice(0, 60));
patched = patched
  .replace(ANN_HTML, '+(env.P_LINES?"":"<tr>"+"<td>"+"<b>"+__WH("w408a27b5e4", "Annual value", [])+"</b>"+"</td>"+"<td style=\\"text-align:right\\">"+"<b>"+(esc(o.annual))+"</b>"+"</td>"+"</tr>")')
  .replace(ANN_PDF, '.concat(env.P_LINES?[]:[[{text:__W("w408a27b5e4", "Annual value", []),bold:true},{text:o.annual,bold:true,alignment:"right"}]])')
  .replace(FLOOR, 's.opts.forEach(function(o){ var t=pTotals(env.P_LINES?{lines:o.lines.filter(function(l){return !/software/i.test(l.svc);})}:o), nm=o.name||"An option";');
writeFileSync(OUT, patched.replace(FEETEXT, FEETEXT + ' if(env.P_NEED&&!trim(String(v==null?"":v))) return "Amount needed";').replace(POPTS, 'B.push({k:"popts",single:s.single||!!env.P_LINES,')
  .replace(LINE, 'return [l.svc,env.P_LINES&&!trim(l.amt)?"Amount needed":v.k==="num"?'));
writeFileSync(WORDING_OUT, JSON.stringify([...pieces.values()], null, 1) + "\n");
console.log(`Wording pieces: ${pieces.size} (written to ${WORDING_OUT}).`);
console.log(`Wrote ${OUT}: ${take.size} names, ${stmts.length} statements.`);
if (unknown.size) console.log("Not found (check ROOTS):", [...unknown].join(", "));
console.log("Uses from the app:", [...injectedUsed].join(", ") || "none");
