// The standard chart file is the one source (round 14, as the master lines in round 12):
// docs/phase3/Closebook-standard-chart-APPROVED.csv says what the database holds after every migration.
// This writes the database test that checks it, from the file. Run:
// node --experimental-strip-types scripts/gen-standard-chart-check.ts
// (tests/closebook-standard-chart.test.ts checks the test is up to date with the file).
// Checked: number, name, type, master line, the master line's name and income tax code, the regular
// method sales tax and the note. The quick method column is not stored in the database (Closebook works
// it out from the regular method), so the file alone holds it.
import { readFileSync, writeFileSync } from "node:fs";

export const OUT = "supabase/tests/closebook_standard_chart_test.sql";
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

// RFC 4180: quoted fields may hold commas and doubled quotes.
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [], f = "", inQ = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQ) { if (c === '"' && text[i + 1] === '"') { f += '"'; i++; } else if (c === '"') inQ = false; else f += c; }
    else if (c === '"') inQ = true;
    else if (c === ",") { row.push(f); f = ""; }
    else if (c === "\n" || c === "\r") { if (c === "\r" && text[i + 1] === "\n") i++; row.push(f); rows.push(row); row = []; f = ""; }
    else f += c;
  }
  if (f || row.length) { row.push(f); rows.push(row); }
  return rows;
}

export function standardChartCheck(csv: string): string {
  const rows = parseCsv(csv).slice(1).filter((r) => r[0]?.trim());
  const values = rows.map((r) => `  (${[0, 1, 2, 3, 4, 5, 6, 8].map((i) => q((r[i] ?? "").trim())).join(", ")})`).join(",\n");
  return `-- GENERATED by scripts/gen-standard-chart-check.ts from docs/phase3/Closebook-standard-chart-APPROVED.csv. Do not edit.
-- The standard chart file is the one source: after every migration, the database's chart accounts are the file's.
\\set ON_ERROR_STOP 1
create temp table expected_chart (number text primary key, name text, account_type text, line_no text, line_name text, income_tax text, sales_tax text, note text);
insert into expected_chart values
${values};
select test.check('the standard chart file has every chart account in the database, and no other',
  (select count(*) from expected_chart) = (select count(*) from public.cb_chart_accounts)
  and not exists (select 1 from expected_chart e where not exists (select 1 from public.cb_chart_accounts c where c.number = e.number)));
select test.check('numbers, names, types, master lines, sales tax and notes: the database says what the file says', not exists (
  select 1 from expected_chart e join public.cb_chart_accounts c using (number)
   where c.name is distinct from e.name or c.account_type is distinct from e.account_type or coalesce(c.line_no, '') is distinct from e.line_no
      or c.tax_default is distinct from e.sales_tax or c.note is distinct from e.note));
select test.check('each account''s master line name and income tax code: the master lines say what the file says', not exists (
  select 1 from expected_chart e join public.cb_chart_accounts c using (number) left join public.cb_master_lines m on m.line_no = c.line_no
   where coalesce(m.name, '') is distinct from e.line_name or coalesce(m.default_tax_code, '') is distinct from e.income_tax));
`;
}

if (process.argv[1]?.endsWith("gen-standard-chart-check.ts")) {
  writeFileSync(OUT, standardChartCheck(readFileSync("docs/phase3/Closebook-standard-chart-APPROVED.csv", "utf8")));
  console.log("Wrote", OUT);
}
