       case when not exists (select 1 from information_schema.tables t where t.table_schema = 'public' and t.table_name = e.table_name) then 'whole table missing' else 'column missing' end as what
  from expected_cols e
 where not exists (select 1 from information_schema.columns c where c.table_schema = 'public' and c.table_name = e.table_name and c.column_name = e.column_name)
union all
select 'function', f.name, 'missing' from expected_funcs f
 where not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'public' and p.proname = f.name)
union all
select 'policy', p.schema_name || '.' || p.table_name || ': ' || p.policy_name, 'missing' from expected_pols p
 where not exists (select 1 from pg_policies x where x.schemaname = p.schema_name and x.tablename = p.table_name and x.policyname = p.policy_name)
union all
select 'rls', c.relname, 'row level security off' from pg_class c join pg_namespace n on n.oid = c.relnamespace
 where n.nspname = 'public' and c.relkind in ('r', 'p') and not c.relrowsecurity
order by 1, 3, 2;
