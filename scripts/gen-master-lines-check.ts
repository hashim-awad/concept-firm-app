// The master lines file is the one source (round 12, Hashim, Nov 14, 2026): docs/phase3/Closebook-master-
// lines-APPROVED.xlsx says what the database holds after every migration. This writes the database test
// that checks it, from the file. Run: node --experimental-strip-types scripts/gen-master-lines-check.ts
// (tests/closebook-master-lines.test.ts checks the test is up to date with the file).
// The original seed (migration 20261111000000) is generated from the Nov 11 copy in docs/phase3/archive.
import { readFileSync, writeFileSync } from "node:fs";
import { readXlsx } from "../src/lib/closebook/xlsx.ts";

export const OUT = "supabase/tests/closebook_master_lines_test.sql";
const str = (v: unknown) => (v === null || v === undefined ? "" : String(v)).trim();
const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function masterLinesCheck(data: Uint8Array): string {
  const rows = (readXlsx(data).find((s) => s.name === "Master lines")?.rows ?? []).slice(1).filter((r) => str(r[0]));
  const values = rows.map((r) => `  (${q(str(r[0]))}, ${q(str(r[1]))}, ${q(str(r[3]))}, ${q(str(r[7]) === "n/a" ? "" : str(r[7]))})`).join(",\n");
  return `-- GENERATED by scripts/gen-master-lines-check.ts from docs/phase3/Closebook-master-lines-APPROVED.xlsx. Do not edit.
-- The master lines file is the one source: after every migration, the database's line names, GIFI names
-- and statement lines are the file's.
\\set ON_ERROR_STOP 1
create temp table expected (line_no text primary key, name text, gifi_name text, statement_line text);
insert into expected values
${values};
select test.check('the master lines file has every line in the database, and no other',
  (select count(*) from expected) = (select count(*) from public.cb_master_lines)
  and not exists (select 1 from expected e where not exists (select 1 from public.cb_master_lines m where m.line_no = e.line_no)));
select test.check('line names, GIFI names and statement lines: the database says what the file says', not exists (
  select 1 from expected e join public.cb_master_lines m using (line_no)
   where m.name is distinct from e.name or m.gifi_name is distinct from e.gifi_name or coalesce(m.statement_line, '') is distinct from e.statement_line));
`;
}

if (process.argv[1]?.endsWith("gen-master-lines-check.ts")) {
  writeFileSync(OUT, masterLinesCheck(readFileSync("docs/phase3/Closebook-master-lines-APPROVED.xlsx")));
  console.log("Wrote", OUT);
}
